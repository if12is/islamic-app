  static String tr(BuildContext context, String key) {
    final languageCode = Localizations.localeOf(context).languageCode;
    final values =
        _localizedValues[languageCode] ?? _localizedValues[_fallbackLanguage]!;
    return values[key] ?? _localizedValues[_fallbackLanguage]![key] ?? key;
  }

  static bool isRtl(BuildContext context) {
    return Localizations.localeOf(context).languageCode == 'ar';
  }

  /// Translate without a [BuildContext].
  ///
  /// Used by background work such as the notification scheduler, which builds
  /// user-facing text long before any widget tree exists.
  ///
  /// [replacements] substitutes `{placeholder}` tokens inside the string.
  static String translate(
    String languageCode,
    String key, {
    Map<String, String> replacements = const {},
  }) {
    final values =
        _localizedValues[languageCode] ?? _localizedValues[_fallbackLanguage]!;
    var result =
        values[key] ?? _localizedValues[_fallbackLanguage]![key] ?? key;

    for (final entry in replacements.entries) {
      result = result.replaceAll('{${entry.key}}', entry.value);
    }
    return result;
  }
}

extension AppLocalizationContext on BuildContext {
  String tr(String key) => AppLocalizations.tr(this, key);

  bool get isAppRtl => AppLocalizations.isRtl(this);

  TextDirection get appTextDirection =>
      isAppRtl ? TextDirection.rtl : TextDirection.ltr;
}
